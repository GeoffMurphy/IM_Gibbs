"""Locating input files.

Everything the notebooks and scripts sample is generated by
:mod:`imgibbs.mock`, so nothing has to be fetched. :data:`DATA_DIR` is where
optional inputs of your own go -- a tabulated beam for
:func:`imgibbs.load_beam_table`, or a cube for ``run_gibbs.py --data``.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np

#: Where optional inputs live. Override with the ``IMGIBBS_DATA`` environment
#: variable; otherwise ``data/`` beside the repository root.
DATA_DIR = Path(os.environ.get(
    'IMGIBBS_DATA', Path(__file__).resolve().parent.parent / 'data'))


def data_path(name: str) -> Path:
    """Absolute path to a file in the data directory. Does not check it exists."""
    return DATA_DIR / name


def load(name: str) -> np.ndarray:
    """Load a ``.npy`` from the data directory."""
    path = data_path(name)
    if not path.exists():
        raise FileNotFoundError(f'{path} not found. Set IMGIBBS_DATA or place '
                                f'the file in {DATA_DIR}.')
    return np.load(path)
